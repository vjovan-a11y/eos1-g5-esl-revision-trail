"""fonts_build.py - put the Andika font inside the page (Jovan, 26 November 2026).

Andika (SIL Open Font Licence, app/fonts/OFL-LICENSE.txt) is a font made for children learning to read: single-storey
a and g, a clear l, I and 1. The woff2 files in app/fonts/ (from the @fontsource/andika package, version 5.3.0) are
written into app/src/99-fonts.css as data URIs, so the page needs no font files beside it and works offline.
Latin, Latin extended and Vietnamese, regular and bold, plus regular italic (the example sentences).
Run from the folder root:  python3 scripts/fonts_build.py"""
import base64, os

LATIN = ('U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, '
         'U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD')
LATIN_EXT = ('U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, '
             'U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF')
VIET = ('U+0102-0103, U+0110-0111, U+0128-0129, U+0168-0169, U+01A0-01A1, U+01AF-01B0, U+0300-0301, U+0303-0304, U+0308-0309, '
        'U+0323, U+0329, U+1EA0-1EF9, U+20AB')
SUBSETS = [('latin', LATIN), ('latin-ext', LATIN_EXT), ('vietnamese', VIET)]
FACES = [('normal', 400), ('normal', 700), ('italic', 400)]

out = ['/* 99-fonts.css - GENERATED by scripts/fonts_build.py from app/fonts/*.woff2 (do not edit by hand).\n'
       '   Andika, SIL Open Font Licence 1.1 (app/fonts/OFL-LICENSE.txt). Used by 99-colour.css on the learning screens. */']
for style, weight in FACES:
    for sub, rng in SUBSETS:
        f = f'app/fonts/andika-{sub}-{weight}-{style}.woff2'
        data = base64.b64encode(open(f, 'rb').read()).decode()
        out.append("@font-face { font-family: 'Andika'; font-style: %s; font-weight: %d; font-display: swap;\n"
                   "  src: url(data:font/woff2;base64,%s) format('woff2');\n  unicode-range: %s; }" % (style, weight, data, rng))
open('app/src/99-fonts.css', 'w').write('\n'.join(out) + '\n')
print('app/src/99-fonts.css', os.path.getsize('app/src/99-fonts.css') // 1024, 'KB')
